from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

_IGNORED_TOP_LEVEL = {".git", "venv", ".venv", "__pycache__", ".pytest_cache", "node_modules"}


def _top_level_entries(project: Path) -> list[str]:
    return sorted(
        p.name + ("/" if p.is_dir() else "") for p in project.iterdir() if p.name not in _IGNORED_TOP_LEVEL
    )


def generate_readme(project: Path) -> str:
    """Build a minimal README.md body from the project's name and top-level layout."""
    entries = _top_level_entries(project)
    lines = [
        f"# {project.name}",
        "",
        f"_Auto-generated by projarchive on {datetime.now(timezone.utc).strftime('%Y-%m-%d')} "
        "because no README.md was found before compressing this project._",
        "",
        "## Contents",
        "",
    ]
    lines += [f"- {entry}" for entry in entries] if entries else ["(empty project directory)"]
    lines.append("")
    return "\n".join(lines)


def ensure_readme(project: Path) -> tuple[Path, bool]:
    """Return (README.md path, whether it was just generated)."""
    readme_path = project / "README.md"
    if readme_path.exists():
        return readme_path, False
    readme_path.write_text(generate_readme(project), encoding="utf-8")
    return readme_path, True
